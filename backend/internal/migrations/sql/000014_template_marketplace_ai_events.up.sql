CREATE TABLE public.ai_point_accounts (
    tenant_id uuid PRIMARY KEY REFERENCES public.tenants(id) ON DELETE CASCADE,
    period_start date NOT NULL,
    granted_points bigint NOT NULL DEFAULT 1000 CHECK (granted_points >= 0),
    consumed_points bigint NOT NULL DEFAULT 0 CHECK (consumed_points >= 0),
    held_points bigint NOT NULL DEFAULT 0 CHECK (held_points >= 0),
    version integer NOT NULL DEFAULT 1,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (consumed_points + held_points <= granted_points)
);

CREATE TABLE public.ai_point_ledger (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    period_start date NOT NULL,
    event_id uuid NOT NULL,
    entry_type varchar(20) NOT NULL CHECK (entry_type IN ('grant','hold','capture','release','adjustment')),
    points bigint NOT NULL CHECK (points > 0),
    reference_type varchar(40) NOT NULL,
    reference_id varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, event_id, entry_type)
);

