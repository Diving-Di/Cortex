CREATE TABLE public.public_profiles (
    tenant_id uuid PRIMARY KEY REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id integer NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
    public_id uuid NOT NULL UNIQUE,
    nickname varchar(40) NOT NULL CHECK (char_length(nickname) BETWEEN 2 AND 40),
    discoverable boolean NOT NULL DEFAULT false,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.writing_templates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    created_by integer NOT NULL REFERENCES public.users(id),
    title varchar(120) NOT NULL,
    description varchar(500) NOT NULL DEFAULT '',
    content_markdown text NOT NULL CHECK (octet_length(content_markdown) BETWEEN 1 AND 65536),
    category varchar(40) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'private' CHECK (status IN ('private','published','withdrawn')),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    UNIQUE (tenant_id, id)
);

CREATE TABLE public.template_publications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL,
    template_id bigint NOT NULL,
    template_version integer NOT NULL,
    title varchar(120) NOT NULL,
    description varchar(500) NOT NULL,
    content_markdown text NOT NULL,
    category varchar(40) NOT NULL,
    content_sha256 char(64) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'published' CHECK (status IN ('published','withdrawn')),
    published_at timestamptz NOT NULL DEFAULT now(),
    withdrawn_at timestamptz,
    UNIQUE (tenant_id, template_id, template_version),
    FOREIGN KEY (tenant_id, template_id) REFERENCES public.writing_templates(tenant_id, id)
);

CREATE TABLE public.published_template_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_template_id uuid NOT NULL,
    source_publication_id bigint NOT NULL UNIQUE REFERENCES public.template_publications(id),
    author_public_id uuid NOT NULL REFERENCES public.public_profiles(public_id),
    author_nickname varchar(40) NOT NULL,
    version integer NOT NULL,
    title varchar(120) NOT NULL,
    description varchar(500) NOT NULL,
    content_markdown text NOT NULL,
    category varchar(40) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'published' CHECK (status IN ('published','withdrawn')),
    published_at timestamptz NOT NULL DEFAULT now(),
    withdrawn_at timestamptz,
    UNIQUE (public_template_id, version)
);
CREATE UNIQUE INDEX uq_published_template_active ON public.published_template_snapshots(public_template_id) WHERE status='published';
CREATE INDEX ix_published_template_list ON public.published_template_snapshots(status, published_at DESC, id DESC);

CREATE TABLE public.template_reactions (
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES public.users(id),
    public_template_id uuid NOT NULL,
    kind varchar(20) NOT NULL CHECK (kind IN ('like','favorite')),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, user_id, public_template_id, kind)
);

CREATE TABLE public.template_usages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES public.users(id),
    public_template_id uuid,
    source_template_id bigint,
    snapshot_version integer NOT NULL,
    note_id integer NOT NULL REFERENCES public.notes(id),
    idempotency_key varchar(128) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, idempotency_key),
    UNIQUE (tenant_id, note_id)
