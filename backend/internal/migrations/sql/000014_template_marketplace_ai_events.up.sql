CREATE TABLE public.ai_flash_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE,
    event_date date NOT NULL,
    timezone varchar(64) NOT NULL DEFAULT 'Asia/Shanghai',
    opens_at timestamptz NOT NULL,
    closes_at timestamptz NOT NULL,
    total_slots integer NOT NULL DEFAULT 10 CHECK (total_slots > 0),
    claimed_slots integer NOT NULL DEFAULT 0 CHECK (claimed_slots >= 0 AND claimed_slots <= total_slots),
    points_cost integer NOT NULL DEFAULT 100 CHECK (points_cost > 0),
    required_streak_days integer NOT NULL DEFAULT 5 CHECK (required_streak_days > 0),
    status varchar(20) NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','open','closed','paused','cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (event_date, timezone),
    CHECK (closes_at > opens_at)
);

CREATE TABLE public.ai_flash_claims (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL REFERENCES public.ai_flash_events(id),
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES public.users(id),
    request_id uuid NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('queued','running','succeeded','failed')),
    points_cost integer NOT NULL,
    streak_days_at_claim integer NOT NULL,
    claimed_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    report_note_id integer REFERENCES public.notes(id),
    error_code varchar(50),
    UNIQUE (event_id, tenant_id),
    UNIQUE (tenant_id, request_id)
);

